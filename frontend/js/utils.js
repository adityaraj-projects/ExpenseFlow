const CURRENCY_SYMBOLS = {
  INR: '₹',
  USD: '$',
  EUR: '€',
  GBP: '£',
  CAD: 'C$',
  AUD: 'A$',
  JPY: '¥'
};

/**
 * Format a numeric amount as currency string.
 * Uses Indian numbering format if currency is INR.
 */
function formatCurrency(amount, currency = 'INR') {
  const num = Number(amount) || 0;
  const symbol = CURRENCY_SYMBOLS[currency] || currency;

  try {
    const formatted = new Intl.NumberFormat(currency === 'INR' ? 'en-IN' : 'en-US', {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    }).format(num);

    return `${symbol}${formatted}`;
  } catch (e) {
    return `${symbol}${num.toFixed(2)}`;
  }
}

/**
 * Format date string into human readable 'DD Mon YYYY'
 */
function formatDate(dateStr) {
  if (!dateStr) return '';
  const d = new Date(dateStr);
  if (isNaN(d.getTime())) return dateStr;

  return d.toLocaleDateString('en-IN', {
    day: 'numeric',
    month: 'short',
    year: 'numeric'
  });
}

/**
 * Format Date object to YYYY-MM-DD for HTML5 date inputs
 */
function formatDateInput(d = new Date()) {
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

/**
 * Debounce helper for live search inputs
 */
function debounce(fn, delay = 300) {
  let timer = null;
  return function (...args) {
    clearTimeout(timer);
    timer = setTimeout(() => fn.apply(this, args), delay);
  };
}

/**
 * Theme Manager (Dark Mode / Light Mode)
 */
function initTheme() {
  const savedTheme = localStorage.getItem('expenseflow_theme') || 'light';
  document.documentElement.setAttribute('data-theme', savedTheme);
  updateThemeIcon(savedTheme);
}

function toggleTheme() {
  const currentTheme = document.documentElement.getAttribute('data-theme') || 'light';
  const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
  document.documentElement.setAttribute('data-theme', newTheme);
  localStorage.setItem('expenseflow_theme', newTheme);
  updateThemeIcon(newTheme);
  window.dispatchEvent(new CustomEvent('themechange', { detail: { theme: newTheme } }));
}

function updateThemeIcon(theme) {
  const btns = document.querySelectorAll('.theme-toggle-btn');
  btns.forEach(btn => {
    btn.innerHTML = theme === 'dark' ? getSvgIcon('sun') : getSvgIcon('moon');
    btn.setAttribute('title', theme === 'dark' ? 'Switch to Light Mode' : 'Switch to Dark Mode');
  });
}

